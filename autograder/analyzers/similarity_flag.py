"""originality: flag suspected copying from classmates, online sources or LLMs.

* Peer copying: winnowed fingerprints against every other file in
  ``corpus_dir`` (see ``autograder.similarity``).
* Online / LLM sources: the same comparison against ``known_sources_dir``.
  It can hold solutions found online and solutions generated by LLMs for this
  problem (``autograder probe-llm`` writes them there), so "copied from
  ChatGPT/Llama" is detected the same way as copying from a peer.
* Stylometric LLM markers ("// Function to ...", doxygen tags, "Time
  complexity: O(n)" ...) are reported as an *informational* flag only. They
  are weak evidence and never change the score.

A pair is flagged when similarity >= ``flag_threshold`` and at least
``min_shared`` fingerprints survive boilerplate removal, or when the
normalised token streams are identical and the program has at least
``min_tokens_identical`` tokens. Tiny programs cannot reliably be told apart.
The assignment's 7-line add.c is token-for-token identical to what an LLM
writes for the same statement, so it is reported but not flagged.
Flags are review signals.

Who copied from whom: when ``corpus_dir`` is not given and the grader keeps the graded programs in
``submissions/<problem>/`` (the browser interface does; the command line with ``--submissions-dir``), that folder
is the corpus. A matching peer is *earlier* or *later* than the program by file modification time: the later
one is the likely copy. In that folder, programs with the same file name are the same student and are never compared.
"""

from __future__ import annotations

import re
from pathlib import Path

from ..csource import parse
from ..similarity import boilerplate, fingerprint, matched_line_ranges, overlap, sequence_ratio
from ..util import hash_files, read_text
from .base import Analyzer, AnalyzerResult, register

LLM_COMMENT_MARKERS = [
    r"^(function|helper function|main function|a function) (to|that|which)\b",
    r"^(read|get|take|scan) (the )?(input|two|user|numbers|values|integers|array)",
    r"^(print|display|output) (the )?(result|sum|output|answer|sorted)",
    r"^(check|verify) (if|whether|for)\b",
    r"^(initialize|declare|define) ",
    r"^(calculate|compute) (the )?",
    r"^(iterate|loop) (through|over)",
    r"^return (the )?(result|sum|0|success)",
    r"^(include|including) (necessary|required|standard)",
    r"@(brief|param|return)",
    r"(time|space) complexity",
    r"^(handle|handling) ",
    r"^edge case",
    r"^example usage",
    r"^(main|driver) (function|code|program)",
]
_MARKERS = [re.compile(p, re.I) for p in LLM_COMMENT_MARKERS]


@register
class SimilarityFlag(Analyzer):
    name = "similarity_flag"
    description = "Copy detection (winnowed fingerprints) against peers, online and LLM-generated solutions"

    def run(self, ctx, params):
        k = int(params.get("k", 5))
        w = int(params.get("window", 4))
        threshold = float(params.get("flag_threshold", 0.85))
        min_shared = int(params.get("min_shared", 8))
        min_tokens_identical = int(params.get("min_tokens_identical", 50))
        common_fraction = float(params.get("common_fraction", 0.5))
        flagged_score = float(params.get("flagged_score", 0.0))
        style_threshold = float(params.get("llm_style_threshold", 0.6))

        me = fingerprint(ctx.csource, k, w)
        own_path = ctx.submission.resolve()
        corpus, same_name = params.get("corpus_dir"), ""
        if not corpus and ctx.submissions_dir:  # the graded programs of this problem, kept by the grader
            corpus, same_name = ctx.submissions_dir / corpus_name(ctx.rules.problem), ctx.submission.name
        peers = self._load_dir(ctx, corpus, exclude=own_path, k=k, w=w, same_name=same_name)
        known = self._load_dir(ctx, params.get("known_sources_dir"), exclude=own_path, k=k, w=w)
        my_time = _mtime(ctx.submission)
        base = None
        if params.get("ignore_reference", True) and ctx.rules.reference_path and ctx.rules.reference_path.is_file():
            base = fingerprint(parse(read_text(ctx.rules.reference_path)), k, w)
        common = boilerplate(base, [fp for _, fp, _ in peers] + [me], common_fraction)
        mine = me.keys - common

        matches = []
        for kind, items in (("peer", peers), ("known_source", known)):
            for path, fp, label in items:
                theirs = fp.keys - common
                shared = mine & theirs
                sim = overlap(mine, theirs)
                exact = me.tokens == fp.tokens and len(me.tokens) > 0
                if exact:
                    sim = 1.0
                order = _order(my_time, _mtime(path)) if kind == "peer" else None
                matches.append({
                    "kind": kind, "file": label, "similarity": round(sim, 4), "shared_fingerprints": len(shared),
                    **({"order": order} if order else {}),
                    "token_sequence_ratio": round(sequence_ratio(me, fp), 4), "identical_tokens": exact,
                    "your_lines": matched_line_ranges(me, shared, k)[:6],
                    "their_lines": matched_line_ranges(fp, shared, k)[:6],
                })
        matches.sort(key=lambda m: (-m["similarity"], m["file"]))
        big_enough = len(me.tokens) >= min_tokens_identical
        flagged = [m for m in matches if m["similarity"] >= threshold
                   and (m["shared_fingerprints"] >= min_shared or (m["identical_tokens"] and big_enough))]

        style = self._llm_style(ctx)
        flags = []
        for m in flagged:
            if m["kind"] == "peer":
                flag = {"type": "suspected_plagiarism", "severity": "high", "peer": m["file"],
                        "similarity": m["similarity"],
                        "message": f"{m['similarity']:.2f} similar to {m['file']} "
                                   f"(your lines {_fmt_ranges(m['your_lines'])}); instructor review needed"}
                if m.get("order") in ("earlier", "later"):
                    flag["order"] = m["order"]
                    flag["likely_copied_from"] = m["file"] if m["order"] == "earlier" else ctx.submission.name
                    flag["message"] += "; " + _direction(m["file"], m["order"])
                flags.append(flag)
            else:
                flags.append({"type": "suspected_online_or_llm_copy", "severity": "high", "source": m["file"],
                              "similarity": m["similarity"],
                              "message": f"{m['similarity']:.2f} similar to known source {m['file']}"})
        if style["score"] >= style_threshold:
            flags.append({"type": "llm_style_markers", "severity": "info", "score": style["score"],
                          "message": f"{style['matching_comments']} of {style['comments']} comments match typical "
                                     f"LLM phrasing (informational only, not penalised)"})

        top = matches[0] if matches else None
        evidence = {
            "max_similarity": top["similarity"] if top else 0.0,
            "flag_threshold": threshold, "min_shared": min_shared,
            "distinctive_fingerprints": len(mine), "boilerplate_removed": len(me.keys & common),
            "corpus_files": len(peers), "known_sources": len(known),
            "corpus_hash": hash_files([p for p, _, _ in peers]),
            "top_matches": matches[:5], "llm_style": style,
        }
        if flagged:
            m = flagged[0]
            who = "classmate file" if m["kind"] == "peer" else "known online/LLM source"
            direction = f" {_direction(m['file'], m['order'])}." if m.get("order") in ("earlier", "later") else ""
            return AnalyzerResult(
                flagged_score, f"FLAGGED: {m['similarity']:.2f} vs {m['file']}",
                f"Your code is {m['similarity']:.2f} similar to {who} {m['file']} (threshold {threshold:.2f}); "
                f"lines {_fmt_ranges(m['your_lines'])} match.{direction} This is flagged for instructor review.",
                evidence, ["Submit your own work; cite any source you adapted."], flags=flags)
        if top is None:
            summary = "no other submissions to compare"
            feedback = "No other submissions to compare with."
        elif top["similarity"] >= threshold:
            summary = f"max similarity {top['similarity']:.2f} (too little distinctive code to flag)"
            feedback = (f"Your program is {top['similarity']:.2f} similar to {top['file']}, but it is too short to "
                        f"tell copying from the one obvious solution, so it is not flagged.")
        else:
            summary = f"max similarity {top['similarity']:.2f}, not flagged"
            feedback = f"No suspicious overlap (max similarity {top['similarity']:.2f} with {top['file']})."
        return AnalyzerResult(1.0, summary, feedback, evidence, flags=flags)

    @staticmethod
    def _load_dir(ctx, rel, exclude: Path, k: int, w: int, same_name: str = ""):
        if not rel:
            return []
        d = ctx.rules.resolve(str(rel))
        if not d.is_dir():
            return []
        out = []
        for path in sorted(d.rglob("*.c"), key=lambda p: p.as_posix()):
            if path.resolve() == exclude or (same_name and path.name == same_name):  # same file name: same student
                continue
            fp = fingerprint(parse(read_text(path)), k, w)
            out.append((path, fp, path.relative_to(d).as_posix()))
        return out

    @staticmethod
    def _llm_style(ctx):
        bodies = [c.body for c in ctx.csource.comments if c.body]
        hits = [b for b in bodies if any(p.search(line) for line in b.split("\n") for p in _MARKERS)]
        n = len(bodies)
        score = (len(hits) / n) * min(1.0, n / 4) if n else 0.0
        return {"score": round(score, 4), "comments": n, "matching_comments": len(hits),
                "examples": [h[:60] for h in hits[:3]]}


def corpus_name(problem: str) -> str:
    """Folder name under ``submissions/`` for a problem (safe to use in a path)."""
    return re.sub(r"[^A-Za-z0-9_.-]", "_", problem).strip("._") or "problem"


def _mtime(path: Path) -> float:
    try:
        return path.stat().st_mtime
    except OSError:
        return 0.0


def _order(mine: float, theirs: float, tolerance: float = 1.0) -> str:
    """Was the other program written before ("earlier") or after ("later") this one?"""
    if not mine or not theirs or abs(mine - theirs) <= tolerance:
        return "unknown"
    return "earlier" if theirs < mine else "later"


def _direction(peer: str, order: str) -> str:
    if order == "earlier":
        return f"{peer} was submitted earlier, so this program is the likely copy"
    return f"{peer} was submitted later, so {peer} is the likely copy"


def _fmt_ranges(ranges) -> str:
    return ", ".join(f"{a}-{b}" if a != b else str(a) for a, b in ranges) or "-"
